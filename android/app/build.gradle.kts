import java.util.Properties

plugins {
    id("com.android.application")
    // The Flutter Gradle Plugin must be applied after the Android and Kotlin Gradle plugins.
    id("dev.flutter.flutter-gradle-plugin")
}

val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
if (keystorePropertiesFile.isFile) {
    keystorePropertiesFile.inputStream().use { keystoreProperties.load(it) }
}

gradle.taskGraph.whenReady {
    val packagesRelease = allTasks.any {
        it.project == project && it.name in setOf("assembleRelease", "bundleRelease", "packageRelease")
    }
    if (packagesRelease) {
        if (!keystorePropertiesFile.isFile) {
            throw GradleException(
                "Release signing is not configured. Create android/key.properties with " +
                    "storeFile, storePassword, keyAlias, and keyPassword for your upload keystore."
            )
        }
        val missing = listOf("storeFile", "storePassword", "keyAlias", "keyPassword")
            .filter { keystoreProperties.getProperty(it).isNullOrBlank() }
        if (missing.isNotEmpty()) {
            throw GradleException("Missing release signing values in android/key.properties: ${missing.joinToString()}.")
        }
        if (!file(keystoreProperties.getProperty("storeFile")).isFile) {
            throw GradleException("The upload keystore specified by storeFile in android/key.properties does not exist.")
        }
    }
}

